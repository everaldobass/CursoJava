package fundamentos;

public class EstruturaIfElse {

    public static void main(String[] args) {
        double nota = 7.3;
        boolean bomComportamento = true;

        if (nota >= 7 && bomComportamento) {
            System.out.println("Aprovado!");
        } else {
            System.out.println("Reprovado!");
        }
    }
    
}
