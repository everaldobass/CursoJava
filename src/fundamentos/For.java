package fundamentos;

// Aula - 22 sobre estrutura de repetição for

/**
 * Como utilizar o laço de repetição for
 */

public class For {

    public static void main(String[] args) {
        
        for (int i = 0; i <= 10; i++) {
            System.out.println("i = " + i);
        }

        System.out.println("Fim do laço For");

    }
    
}
